const dicts = { de, en };
let lang = load('lang', null) || (navigator.language?.startsWith('de') ? 'de' : config.defaultLang);
if (!dicts[lang]) lang = 'de';
document.documentElement.lang = lang;

export const getLang = () => lang;

export function setLang(next) {
  if (!dicts[next] || next === lang) return;
  lang = next;
  save('lang', lang);
  document.documentElement.lang = lang;
  emit('lang', lang);
}

export const toggleLang = () => setLang(lang === 'de' ? 'en' : 'de');

export function t(key, vars = {}) {
  const text = dicts[lang][key] ?? dicts.de[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

/** Alle Elemente mit data-i18n neu beschriften (nach Sprachwechsel). */
export function translate(root) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-i18n-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nLabel));
  });
}
